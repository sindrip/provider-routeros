// gen emits typed Go accessors from the pinned IR.
//
// This is the spike that answers whether the IR carries enough to generate
// against. It covers a handful of menus chosen to exercise every case that
// matters — a keyed list, an unkeyed one, an ordered chain, and a read-only
// singleton — rather than the whole device.
//
// The output depends on nothing but the standard library. rest.Record is
// map[string]string underneath, so a caller passes one straight in without
// this package having to import rest, which keeps the generated code off
// rest's release-candidate toolchain.
//
//	cd gen && go run -buildvcs=false . && gofmt -w routeros
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	"github.com/sindrip/provider-routeros/schema"
)

// spike is the subset to emit.
//
// The first four were chosen to exercise every case that matters: a keyed
// list, an unkeyed one, an ordered chain, and a read-only singleton. The rest
// are the menus the OTel collector scrapes, which nobody chose for the
// generator's convenience — they are here to find out what breaks.
var spike = []string{
	"/ip/address",         // list, writable, no proven key: identity is a hole
	"/interface/bridge",   // list, writable, name proven unique, hex-valued field
	"/ip/firewall/filter", // ordered chain, dense with booleans and enums
	"/system/resource",    // singleton, read-only, durations and counters

	"/interface",           // the collector's counters; a menu with no add
	"/routing/bgp/session", // read-only rows, dotted keys, a present-but-empty bool
	"/system/health",       // sensor rows on iron, a settings singleton on CHR
	"/system/routerboard",  // absent entirely on CHR
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	ir, err := schema.Load()
	if err != nil {
		return err
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen from RouterOS %s. DO NOT EDIT.\n\n", ir.RouterOSVersion)
	b.WriteString("// Package routeros is a typed view of a few RouterOS menus.\n")
	b.WriteString("//\n")
	b.WriteString("// Every value RouterOS returns is a string; these types say what each one\n")
	b.WriteString("// means, on the router's own authority rather than a schema written by hand.\n")
	b.WriteString("package routeros\n\n")
	b.WriteString("import \"time\"\n\n")

	var absent []string
	for _, path := range spike {
		m, ok := ir.Menu(path)
		if !ok {
			// The IR knows the menus the probed device had, and no others.
			// /system/routerboard does not exist on CHR — a virtual router has
			// no board — so there is nothing here to type. Saying so in the
			// generated file is the whole point; inventing the menu from a
			// manual page is what this pipeline exists to avoid.
			absent = append(absent, path)
			continue
		}
		emitMenu(&b, m)
	}
	if len(absent) > 0 {
		fmt.Fprintf(&b, "// Requested but absent from the IR, which was probed on %s:\n", ir.RouterOSVersion)
		for _, path := range absent {
			fmt.Fprintf(&b, "//   %s\n", path)
		}
		b.WriteString("// A menu the probed device does not have cannot be typed from it.\n")
		b.WriteString("// Generating one anyway would mean sourcing it from somewhere with no\n")
		b.WriteString("// authority over what this router accepts.\n\n")
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		// Write it anyway so the syntax error is readable.
		_ = os.WriteFile(filepath.Join("routeros", "routeros.go"), b.Bytes(), 0o644) //nolint:gosec // generated source
		return fmt.Errorf("formatting generated source: %w", err)
	}
	if err := os.MkdirAll("routeros", 0o750); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join("routeros", "routeros.go"), src, 0o644); err != nil { //nolint:gosec // generated source
		return err
	}
	fmt.Fprintf(os.Stderr, "emitted %d of %d menus\n", len(spike)-len(absent), len(spike))
	return nil
}

func emitMenu(b *bytes.Buffer, m schema.Menu) {
	name := typeName(m.Path)
	emitEnums(b, name, m)
	emitDoc(b, name, m)
	emitStruct(b, name, m)
	emitDecode(b, name, m)
	emitEncode(b, name, m)
}

// emitEnums gives each closed vocabulary its own named type, so an invalid
// value is a compile error rather than a silent 400 from the router.
func emitEnums(b *bytes.Buffer, name string, m schema.Menu) {
	for _, f := range m.Fields {
		if f.Kind != schema.KindEnum || f.Bool || len(f.Values) == 0 {
			continue
		}
		en := name + goName(f.Name)
		fmt.Fprintf(b, "// %s is the vocabulary the router states for %s %s.\n", en, m.Path, f.Name)
		fmt.Fprintf(b, "type %s string\n\nconst (\n", en)
		seen := map[string]int{}
		for _, v := range f.Values {
			cn := en + goName(v)
			// Two spellings can still land on one identifier; keeping both
			// matters more than pretty names, so the later one is numbered.
			if n := seen[cn]; n > 0 {
				seen[cn] = n + 1
				cn = fmt.Sprintf("%s%d", cn, n+1)
			} else {
				seen[cn] = 1
			}
			fmt.Fprintf(b, "\t%s %s = %q\n", cn, en, v)
		}
		b.WriteString(")\n\n")
	}
}

func emitDoc(b *bytes.Buffer, name string, m schema.Menu) {
	fmt.Fprintf(b, "// %s is %s.\n//\n", name, m.Path)
	fmt.Fprintf(b, "// %s, %s.", m.Class, writability(m))
	switch {
	case m.Identity.Key != "":
		fmt.Fprintf(b, " Rows are addressable by %s, which this RouterOS enforces unique.\n", m.Identity.Key)
	case m.Rows():
		fmt.Fprintf(b, " No field is a proven unique key here (%s), so a caller\n// addressing rows needs one of its own.\n", m.Identity.Verdict)
	default:
		b.WriteString("\n")
	}
	fmt.Fprintf(b, "const %sPath = %q\n\n", name, m.Path)
}

func emitStruct(b *bytes.Buffer, name string, m schema.Menu) {
	var skipped []string
	for _, f := range m.Fields {
		if skip(f) {
			skipped = append(skipped, f.Name)
		}
	}
	if len(skipped) == len(m.Fields) && len(m.Fields) > 0 {
		// Nothing to emit, and silence would read as "this menu has no
		// fields" rather than "the router would not describe them".
		fmt.Fprintf(b, "// The router states no type for any of the %d fields here, so there is\n", len(m.Fields))
		b.WriteString("// nothing to generate. A read-only property of a menu that holds no rows\n")
		b.WriteString("// has no console position to ask about: `set` will not take it and\n")
		b.WriteString("// `print where` has nothing to filter. Typing it needs evidence of a\n")
		b.WriteString("// different kind — the values themselves — which the IR does not yet carry.\n")
	} else if len(skipped) > 0 {
		fmt.Fprintf(b, "// Omitted, the router having stated no type: %s.\n", strings.Join(skipped, ", "))
	}

	fmt.Fprintf(b, "type %s struct {\n", name)
	if m.Rows() {
		b.WriteString("\t// ID is the router's own row handle. It is reassigned when a row is\n")
		b.WriteString("\t// deleted and recreated, so it addresses a row and does not identify one.\n")
		b.WriteString("\tID string\n\n")
	}
	for _, f := range m.Fields {
		if skip(f) {
			continue
		}
		fmt.Fprintf(b, "\t%s %s // %s%s\n", goName(f.Name), goType(name, f), f.Name, note(f))
	}
	b.WriteString("}\n\n")
}

func emitDecode(b *bytes.Buffer, name string, m schema.Menu) {
	fmt.Fprintf(b, "// Decode%s reads one record as the router returned it.\n", name)
	fmt.Fprintf(b, "func Decode%s(r map[string]string) %s {\n\tvar v %s\n", name, name, name)
	if m.Rows() {
		b.WriteString("\tv.ID = r[\".id\"]\n")
	}
	for _, f := range m.Fields {
		if skip(f) {
			continue
		}
		fmt.Fprintf(b, "\tv.%s = %s\n", goName(f.Name), decodeExpr(name, f))
	}
	b.WriteString("\treturn v\n}\n\n")
}

func emitEncode(b *bytes.Buffer, name string, m schema.Menu) {
	writables := 0
	for _, f := range m.Fields {
		if !skip(f) && f.Access == schema.Writable {
			writables++
		}
	}
	fmt.Fprintf(b, "// Encode returns the writable fields as the router expects them.\n")
	if writables == 0 {
		fmt.Fprintf(b, "// %s has none: the device maintains this menu.\n", name)
	} else {
		b.WriteString("// Read-only fields are omitted; sending one back is how a caller\n")
		b.WriteString("// discovers that the router rejects unknown parameters.\n")
	}
	fmt.Fprintf(b, "func (v %s) Encode() map[string]string {\n\tr := map[string]string{}\n", name)
	for _, f := range m.Fields {
		if skip(f) || f.Access != schema.Writable {
			continue
		}
		fmt.Fprintf(b, "\tr[%q] = %s\n", f.Name, encodeExpr(f))
	}
	b.WriteString("\treturn r\n}\n\n")
}

// decodeExpr is the expression that reads one field out of a raw record.
func decodeExpr(menu string, f schema.Field) string {
	switch {
	case f.Bool:
		return fmt.Sprintf("parseBool(r, %q)", f.Name)
	case isDuration(f):
		return fmt.Sprintf("parseDuration(r[%q])", f.Name)
	case isInteger(f):
		return fmt.Sprintf("parseInt(r[%q])", f.Name)
	case f.Kind == schema.KindEnum && len(f.Values) > 0:
		return fmt.Sprintf("%s(r[%q])", menu+goName(f.Name), f.Name)
	default:
		return fmt.Sprintf("r[%q]", f.Name)
	}
}

// encodeExpr is the expression that renders one field back onto the wire.
func encodeExpr(f schema.Field) string {
	g := "v." + goName(f.Name)
	switch {
	case f.Bool:
		return "formatBool(" + g + ")"
	case isDuration(f):
		return "formatDuration(" + g + ")"
	case isInteger(f):
		return "formatInt(" + g + ")"
	case f.Kind == schema.KindEnum && len(f.Values) > 0:
		return "string(" + g + ")"
	default:
		return g
	}
}

// skip drops fields a generator has no business emitting.
//
// KindUnknown means the router declined to describe the field, and inventing
// a type for it is exactly what the IR exists to prevent. In practice these
// are creation-time console arguments such as copy-from and place-before,
// which are never read back as properties.
func skip(f schema.Field) bool { return f.Kind == schema.KindUnknown }

func note(f schema.Field) string {
	var parts []string
	if f.Access == schema.ReadOnly {
		parts = append(parts, "read-only")
	}
	if f.Type != "" {
		parts = append(parts, f.Type)
	}
	if len(parts) == 0 {
		return ""
	}
	return " (" + strings.Join(parts, ", ") + ")"
}

func writability(m schema.Menu) string {
	if m.Writable {
		return "writable"
	}
	return "read-only"
}

func isDuration(f schema.Field) bool {
	return f.Kind == schema.KindScalar && strings.Contains(f.Type, "time interval")
}

func isInteger(f schema.Field) bool {
	return f.Kind == schema.KindScalar && strings.Contains(f.Type, "integer number") &&
		!strings.Contains(f.Type, "IP address")
}

func goType(menu string, f schema.Field) string {
	switch {
	case f.Bool:
		return "bool"
	case isDuration(f):
		return "time.Duration"
	case isInteger(f):
		return "int64"
	case f.Kind == schema.KindEnum && len(f.Values) > 0:
		return menu + goName(f.Name)
	default:
		return "string"
	}
}

func typeName(path string) string {
	parts := strings.Split(strings.TrimPrefix(path, "/"), "/")
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(goName(p))
	}
	return b.String()
}

// goName turns a RouterOS identifier into a Go one. RouterOS is fond of names
// Go cannot spell: 6to4-interface, 3gpp-info, 802.3-sap, and enum values that
// begin with ! because the vocabulary includes negations — a firewall mark can
// be no-mark or !no-mark, which are different values and must not collapse
// onto one constant.
func goName(s string) string {
	var prefix string
	if strings.HasPrefix(s, "!") {
		prefix, s = "Not", strings.TrimPrefix(s, "!")
	}
	var b strings.Builder
	upper := true
	for _, r := range s {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			upper = true
		case upper:
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		default:
			b.WriteRune(r)
		}
	}
	out := prefix + b.String()
	if out == "" {
		return "Empty"
	}
	if unicode.IsDigit(rune(out[0])) {
		// A leading digit is not a Go identifier; N reads better than an
		// underscore and keeps the original visible in the field comment.
		out = "N" + out
	}
	// No keyword check: every identifier here is capitalised, and Go's
	// keywords are all lower case, so one can never collide. Comparing the
	// lower-cased form instead was worse than useless — it turned every
	// "interface" into "Interface_".
	return out
}
